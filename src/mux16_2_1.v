`timescale 1ns / 1ps
//////////////////////////////////////////////////////////////////////////////////
// 16 bit 2 to 1 multiplexor
//////////////////////////////////////////////////////////////////////////////////

module mux16_2_1(
    output [15:0] out,
    input [15:0] a,
    input [15:0] b,
    input sel
    );
    mux4_2_1 aa(out[3:0],   a[3:0],   b[3:0],   sel);
    mux4_2_1 bb(out[7:4],   a[7:4],   b[7:4],   sel);
    mux4_2_1 cc(out[11:8],  a[11:8],  b[11:8],  sel);
    mux4_2_1 dd(out[15:12], a[15:12], b[15:12], sel);
endmodule
