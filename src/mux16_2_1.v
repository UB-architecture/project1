`timescale 1ns / 1ps
//////////////////////////////////////////////////////////////////////////////////
// 16 bit 2 to 1 multiplexor
//////////////////////////////////////////////////////////////////////////////////

module mux16_2_1(
    output [15:0] out,
    input [15:0] a,
    input [15:0] b,
    input sel
    );
    mux4_2_1(out[3:0],   a[3:0],   b[3:0],   sel);
    mux4_2_1(out[4:7],   a[4:7],   b[4:7],   sel);
    mux4_2_1(out[8:11],  a[8:11],  b[8:11],  sel);
    mux4_2_1(out[12:15], a[12:15], b[12:15], sel);
endmodule
